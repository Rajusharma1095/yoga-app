#!/usr/bin/env python3
"""Build content/poses.json and content/POSE-STEPS.md from the source files.

Sources (edit these, never the generated files):
  poses.csv        - 40 poses: names, category, difficulty, goals, timing, flags
  avoid-rules.csv  - AVOID / CAUTION rules per pose per health condition
  pose-steps.json  - step-by-step instructions, common mistake, easier version

Run after any edit (e.g. once the yoga therapist flips rows to APPROVED):
  python3 content/build.py
"""
import csv, json, pathlib, collections, sys

HERE = pathlib.Path(__file__).parent

def load_poses():
    poses, order = {}, []
    with open(HERE / "poses.csv", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            slug = r["slug"]
            order.append(slug)
            poses[slug] = {
                "id": int(r["id"]), "slug": slug,
                "name": {"en": r["name_en"], "hi": r["name_hi"], "sa": r["name_sanskrit"]},
                "category": r["category"], "difficulty": int(r["difficulty"]),
                "goals": [g for g in r["goals"].split("|") if g],
                "defaultSeconds": int(r["default_seconds"]),
                "perSide": r["per_side"] == "yes",
                "flags": [x for x in r["flags"].split("|") if x],
                "shootBlock": r["shoot_block"], "status": r["status"],
                "clipUrl": None, "audio": {"hi": None, "en": None},
                "steps": None, "mistake": None, "easier": None, "benefit": None,
                "avoid": [],
            }
    return poses, order

def main():
    poses, order = load_poses()
    problems = []

    with open(HERE / "avoid-rules.csv", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            slug = r["pose_slug"]
            if slug not in poses:
                problems.append(f"avoid-rules.csv: unknown pose '{slug}'")
                continue
            if r["level"] not in ("AVOID", "CAUTION"):
                problems.append(f"{slug}: bad level '{r['level']}'")
            alt = r["alternative_slug"] or None
            if alt and alt not in poses:
                problems.append(f"{slug}: unknown alternative '{alt}'")
            poses[slug]["avoid"].append({
                "condition": r["condition"], "level": r["level"],
                "reasonHi": r["reason_hi"], "alternative": alt, "status": r["status"],
            })

    steps = json.load(open(HERE / "pose-steps.json", encoding="utf-8"))
    for slug, s in steps.items():
        if slug not in poses:
            problems.append(f"pose-steps.json: unknown pose '{slug}'")
            continue
        poses[slug].update(steps=s["steps"], mistake=s["mistake"],
                           easier=s["easier"], benefit=s["benefit"])
    for slug in order:
        if not poses[slug]["steps"]:
            problems.append(f"{slug}: no steps written yet")

    ordered = [poses[s] for s in order]
    json.dump({"version": 2, "generatedBy": "content/build.py",
               "sources": ["poses.csv", "avoid-rules.csv", "pose-steps.json"],
               "poses": ordered},
              open(HERE / "poses.json", "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)

    write_markdown(ordered)

    cat = collections.Counter(p["category"] for p in ordered)
    diff = collections.Counter(p["difficulty"] for p in ordered)
    rules = sum(len(p["avoid"]) for p in ordered)
    approved = sum(1 for p in ordered if p["status"] == "APPROVED")
    print(f"poses {len(ordered)} | rules {rules} | approved {approved}/{len(ordered)}")
    print("category", dict(cat), "| difficulty", dict(diff))
    print("safe for everyone:", [p["slug"] for p in ordered if not p["avoid"]])
    if problems:
        print("\nPROBLEMS:")
        for p in problems:
            print("  -", p)
        return 1
    print("\nno problems found")
    return 0

BLOCKS = {"A": "Block A — Standing", "B": "Block B — Hands & Knees",
          "C": "Block C — Prone", "D": "Block D — Supine", "E": "Block E — Seated"}

def write_markdown(ordered):
    L = ["# Pose Steps — all 40 poses", "",
         "Generated by `content/build.py` — **edit `pose-steps.json`, not this file.**", "",
         "Ye content app ke pose detail screen pe dikhta hai, aur shoot ke waqt aapka",
         "reference hai. Shoot block ke order mein laga hai, taaki shoot ke din seedha",
         "upar se neeche chal sako.", ""]
    for block, title in BLOCKS.items():
        group = [p for p in ordered if p["shootBlock"] == block]
        L += [f"## {title} ({len(group)} poses)", ""]
        for p in group:
            n = p["name"]
            side = " · dono side" if p["perSide"] else ""
            L += [f"### {p['id']:02d}. {n['en']} — {n['hi']}", "",
                  f"`{p['slug']}` · {n['sa']} · {p['category']} · difficulty {p['difficulty']}"
                  f" · {p['defaultSeconds']}s{side} · status **{p['status']}**", ""]
            if p["steps"]:
                L += ["**हिंदी steps**", ""]
                L += [f"{i}. {s}" for i, s in enumerate(p["steps"]["hi"], 1)]
                L += ["", "**English steps**", ""]
                L += [f"{i}. {s}" for i, s in enumerate(p["steps"]["en"], 1)]
                L += ["",
                      f"- ❌ **Common galti:** {p['mistake']['hi']}",
                      f"  _{p['mistake']['en']}_",
                      f"- 🟢 **Aasaan version:** {p['easier']['hi']}",
                      f"  _{p['easier']['en']}_",
                      f"- ✅ **Fayda:** {p['benefit']['hi']}",
                      f"  _{p['benefit']['en']}_", ""]
            if p["avoid"]:
                L += ["**🔴 Ye pose na karein agar**", "",
                      "| Condition | Level | Kyun | Alternative |",
                      "|---|---|---|---|"]
                for a in p["avoid"]:
                    L.append(f"| `{a['condition']}` | **{a['level']}** | {a['reasonHi']} "
                             f"| {'`'+a['alternative']+'`' if a['alternative'] else '—'} |")
                L.append("")
            else:
                L += ["**🟢 Koi avoid-rule nahi — har condition mein safe.**", ""]
            L.append("---")
            L.append("")
    (HERE / "POSE-STEPS.md").write_text("\n".join(L), encoding="utf-8")

if __name__ == "__main__":
    sys.exit(main())
